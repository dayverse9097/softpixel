#!/usr/bin/env bash
# Creates the .env file for the production stack. Run ONCE on the server, in the deploy folder:
#   ./init-env.sh
# It asks for your domains and storage details, and generates every secret with openssl.
set -euo pipefail
cd "$(dirname "$0")"

[ -e .env ] && { echo ".env already exists. Edit it by hand, or delete it to start again." >&2; exit 1; }
command -v openssl >/dev/null || { echo "Please install openssl first." >&2; exit 1; }

ask() { local v; read -r -p "$1: " v; printf '%s' "$v"; }
ask_secret() { local v; read -r -s -p "$1: " v; echo >&2; printf '%s' "$v"; }
host_ok() { [[ "$1" =~ ^([a-z0-9]([a-z0-9-]*[a-z0-9])?\.)+[a-z]{2,}$ ]]; }

APP_HOST="$(ask 'App domain (for example play.example.com)')"
API_HOST="$(ask 'API domain (for example api.example.com)')"
GAMES_HOST="$(ask 'Games domain, a DIFFERENT website name (for example nexplay-games.example)')"
for h in "$APP_HOST" "$API_HOST" "$GAMES_HOST"; do host_ok "$h" || { echo "'$h' does not look like a domain name." >&2; exit 1; }; done
[ "$APP_HOST" != "$GAMES_HOST" ] || { echo "The games domain must differ from the app domain." >&2; exit 1; }
ACME_EMAIL="$(ask 'Email address for HTTPS certificates')"

echo "Storage: a PRIVATE bucket on any S3-compatible service (Cloudflare R2, Backblaze B2, AWS S3...)." >&2
S3_ENDPOINT="$(ask 'S3 endpoint URL (leave empty for AWS S3)')"
S3_REGION="$(ask 'S3 region (use auto for Cloudflare R2)')"
S3_BUCKET="$(ask 'Bucket name')"
S3_ACCESS_KEY_ID="$(ask 'Access key id')"
S3_SECRET_ACCESS_KEY="$(ask_secret 'Secret access key (hidden)')"

umask 077
cat > .env <<ENV
# Generated by init-env.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ). Keep this file private: it holds every secret.
APP_HOST=$APP_HOST
API_HOST=$API_HOST
GAMES_HOST=$GAMES_HOST
ACME_EMAIL=$ACME_EMAIL

ADMIN_DB_PASSWORD=$(openssl rand -hex 24)
APP_DB_PASSWORD=$(openssl rand -hex 24)
PUBLIC_DB_PASSWORD=$(openssl rand -hex 24)

SESSION_SECRET=$(openssl rand -hex 32)
PREVIEW_SECRET=$(openssl rand -hex 32)
ENCRYPTION_KEY=$(openssl rand -hex 32)

S3_ENDPOINT=$S3_ENDPOINT
S3_REGION=$S3_REGION
S3_BUCKET=$S3_BUCKET
S3_ACCESS_KEY_ID=$S3_ACCESS_KEY_ID
S3_SECRET_ACCESS_KEY=$S3_SECRET_ACCESS_KEY

# Set by deploy.sh
NEXPLAY_IMAGE=
NEXPLAY_TOOLS_IMAGE=
ENV
chmod 600 .env
echo ".env created. Back it up somewhere safe (a password manager): losing ENCRYPTION_KEY locks admins out of two-factor." >&2
